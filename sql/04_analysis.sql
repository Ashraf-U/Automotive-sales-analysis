-- 24. Find employees/customers who have spent more than the average customer spending.

SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    SUM(o.selling_price * o.quantity) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name
HAVING SUM(o.selling_price * o.quantity) > (
    SELECT AVG(selling_price)
    FROM orders
)
ORDER BY total_spending DESC;

-- 25. Rank all vehicle models according to their total sales revenue. 

SELECT
    v.model,
    SUM(o.selling_price * o.quantity) AS total_revenue,
    RANK() OVER (
        ORDER BY SUM(o.selling_price * o.quantity) DESC
    ) AS revenue_rank
FROM vehicles v
JOIN orders o
    ON v.vehicle_id = o.vehicle_id
GROUP BY v.vehicle_id, v.model
ORDER BY revenue_rank;

-- 26. Rank vehicles within each brand based on their list price.


SELECT vehicle_id, brand, model,
RANK() OVER(PARTITION BY brand ORDER BY list_price DESC) AS price_rank
FROM vehicles;

-- 27. Find the highest-revenue vehicle model for each brand.

SELECT brand,model,total_revenue
FROM 
(SELECT 
v.brand, v.model,
SUM(o.selling_price) AS total_revenue,
RANK() OVER (PARTITION BY v.brand ORDER BY SUM(o.selling_price) DESC ) AS rn
FROM vehicles v
JOIN orders o
ON v.vehicle_id=o.vehicle_id
GROUP BY v.brand , v.model

) AS ranked
WHERE rn=1;


