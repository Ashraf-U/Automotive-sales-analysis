-- 29. CREATE A RESULT CONTAINING dealer_name, total_orders, total_revenue,average_order_value,dealer_rank

SELECT d.dealer_id, d.dealer_name, COUNT(o.order_id), SUM(o.selling_price), 
AVG(o.selling_price) ,
RANK() OVER(ORDER BY SUM(o.selling_price) DESC) AS dealer_rank
FROM dealers d
JOIN orders o
ON
d.dealer_id= o.dealer_id
GROUP BY  d.dealer_id
ORDER BY dealer_rank; 

-- 30. "Which vehicle brands and models are performing best, and which dealerships are contributing the most revenue?"
-- Brand, Model, Number of Orders, Total Revenue, Average Selling Price, Rank Within Brand

SELECT
    brand,
    model,
    number_of_orders,
    total_revenue,
    average_selling_price,
    RANK() OVER (
        PARTITION BY brand
        ORDER BY total_revenue DESC
    ) AS rank_within_brand
FROM (
    SELECT
        v.brand,
        v.model,
        COUNT(o.order_id) AS number_of_orders,
        SUM(o.selling_price * o.quantity) AS total_revenue,
        AVG(o.selling_price) AS average_selling_price
    FROM vehicles v
    JOIN orders o
        ON v.vehicle_id = o.vehicle_id
    GROUP BY v.brand, v.vehicle_id, v.model
) AS model_summary
ORDER BY brand, rank_within_brand;

